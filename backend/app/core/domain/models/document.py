from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
import uuid

from app.core.domain.enum.document_status import DocumentStatus, ProcessingStage


@dataclass
class DocumentChunk:
    """Represents a discrete semantic chunk extracted from a source document.

    Attributes:
        chunk_id: Unique UUID identifier for the chunk.
        text: Raw textual payload of the chunk.
        index: Positional index in the document stream.
        metadata: Key-value context attributes (page, bounding boxes).
        embedding: Vector representation generated by embedding models.
    """

    chunk_id: str
    text: str
    index: int
    metadata: Dict[str, Any] = field(default_factory=dict)
    embedding: Optional[List[float]] = None


@dataclass
class SimilarityScore:
    """Detailed vector similarity and cross-reference evaluation metrics.

    Attributes:
        target_document_id: Reference document UUID.
        cosine_similarity: Vector space cosine similarity [0.0 - 1.0].
        semantic_confidence: Confidence score synthesized by LLM evaluation.
        matched_chunks: Subset of aligned chunk matches.
    """

    target_document_id: str
    cosine_similarity: float
    semantic_confidence: float
    matched_chunks: List[Dict[str, Any]] = field(default_factory=list)


@dataclass
class SemanticEquivalenceResult:
    """Domain entity encapsulating the complete equivalence outcome between documents.

    Attributes:
        analysis_id: Unique UUID of the evaluation run.
        source_document_id: Ingested source document ID.
        candidate_document_id: Target candidate compared against.
        status: High-level classification status (EQUIVALENT, DIVERGENT, etc.).
        overall_score: Consolidated similarity metric [0.0 - 1.0].
        explanation: LLM-generated rationale explaining legal and semantic alignment.
        divergence_points: List of clauses or semantic points identified as divergent.
        created_at: ISO timestamp of analysis completion.
    """

    analysis_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    source_document_id: str = ""
    candidate_document_id: str = ""
    status: DocumentStatus = DocumentStatus.PENDING
    overall_score: float = 0.0
    explanation: str = ""
    divergence_points: List[str] = field(default_factory=list)
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))


@dataclass
class Document:
    """Root aggregate representing an ingested document in the equivalence pipeline.

    Attributes:
        document_id: Unique identifier of the document entity.
        filename: Original file name.
        raw_bytes: Raw binary content for OCR parsing.
        extracted_text: Extracted plain text post-OCR.
        chunks: List of segmented semantic chunks.
        status: Ingestion and processing state.
        stage: Current workflow stage within LangGraph.
    """

    document_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    filename: str = ""
    raw_bytes: bytes = b""
    extracted_text: str = ""
    chunks: List[DocumentChunk] = field(default_factory=list)
    status: DocumentStatus = DocumentStatus.PENDING
    stage: ProcessingStage = ProcessingStage.OCR_EXTRACTION
